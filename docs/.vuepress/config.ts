const HOSTNAME = "https://www.purgecss.com";

/**
 * Vercel serves the site with `cleanUrls: true` and `trailingSlash: false`,
 * so `/introduction.html` and `/fr/` redirect to `/introduction` and `/fr`.
 * Canonical links, Open Graph URLs, hreflang links and the sitemap must name
 * the final URL, not the one that redirects.
 */
const toCleanUrl = (url: string): string =>
  url.replace(
    /^(https:\/\/www\.purgecss\.com)(\/[^"'<>\s]*)?$/,
    (_, host: string, routePath = "/") => {
      const clean = routePath.replace(/\.html$/, "").replace(/\/+$/, "");
      return `${host}${clean || "/"}`;
    },
  );

const pageUrl = (page: Page): string => toCleanUrl(`${HOSTNAME}${page.path}`);

/** Rewrites every absolute URL in canonical, alternate and og:url tags. */
const cleanHeadUrls = (head: HeadConfig[]): void => {
  for (const [tag, attrs] of head) {
    if (tag === "link" && typeof attrs.href === "string") {
      attrs.href = toCleanUrl(attrs.href);
    }
    if (
      tag === "meta" &&
      (attrs.property === "og:url" || attrs.name === "og:url") &&
      typeof attrs.content === "string"
    ) {
      attrs.content = toCleanUrl(attrs.content);
    }
  }
};

/** First prose paragraph of an API Documenter page, as plain text. */
const apiReferenceSummary = (markdown: string): string | undefined => {
  // API Documenter writes CRLF line endings. The summary is the prose between
  // the page heading and the signature, the first table or the next heading.
  const blocks = markdown.split(/(?:\r?\n){2,}/).map((block) => block.trim());
  const start = blocks.findIndex((block) => block.startsWith("## "));
  let paragraph: string | undefined;
  for (const block of start === -1 ? [] : blocks.slice(start + 1)) {
    if (/^(#|\*\*|<|```)/.test(block)) break;
    if (/[a-z]/i.test(block)) {
      paragraph = block;
      break;
    }
  }
  if (!paragraph) return undefined;
  const text = paragraph
    .replace(/<!--.*?-->/g, "")
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/[`*_]/g, "")
    .replace(/&gt;/g, ">")
    .replace(/&lt;/g, "<")
    .replace(/\s+/g, " ")
    .trim();
  return text || undefined;
};

const truncate = (text: string, max = 160): string =>
  text.length > max ? `${text.slice(0, max - 1).trimEnd()}…` : text;

/**
 * Pages generated by API Documenter start with a breadcrumb and an h2 and
 * have no frontmatter, so they would all share the bare site title and get a
 * description made of the breadcrumb. Use their heading and summary instead.
 * The same type is often exported by several packages, so the title names
 * the package (`/api-reference/purgecss-browser.complexsafelist.html`).
 */
const apiReferenceMetaPlugin: PluginObject = {
  name: "purgecss-api-reference-meta",
  extendsPage: (page) => {
    if (!page.path.startsWith("/api-reference/")) return;
    // The markdown is generated and gitignored, so "Edit this page" would
    // link to a file that does not exist on GitHub.
    page.frontmatter.editLink = false;
    const heading = page.headers[0]?.title;
    const [packageName, member] = page.path
      .slice("/api-reference/".length)
      .replace(/\.html$/, "")
      .split(/\.(.*)/);
    const title = heading
      ? member
        ? `${heading} (${packageName})`
        : heading
      : "API Reference";
    if (!page.frontmatter.title) {
      page.title = title;
      page.data.title = title;
      page.routeMeta.title = title;
    }
    // `/api-reference/` itself
    if (!packageName || packageName === "index") {
      page.frontmatter.description =
        "API reference for the PurgeCSS packages: purgecss, the PostCSS, webpack, gulp and Rollup plugins, the browser build and the extractors.";
      return;
    }
    // Options and UserDefinedOptions share their doc comments, so the
    // description starts with the member to stay unique.
    const summary = apiReferenceSummary(page.content);
    page.frontmatter.description = truncate(
      summary
        ? `${member ? title : `${packageName} package`}: ${summary}`
        : `${title}, from the PurgeCSS API reference.`,
    );
  },
};

/** Rewrites the generated sitemap to the clean URLs Vercel serves. */
const cleanSitemapUrlsPlugin: PluginObject = {
  name: "purgecss-clean-sitemap-urls",
  onGenerated: async (app) => {
    const file = app.dir.dest("sitemap.xml");
    if (!(await fs.pathExists(file))) return;
    const xml = await fs.readFile(file, "utf-8");
    await fs.writeFile(
      file,
      xml.replace(/https:\/\/www\.purgecss\.com\/[^"'<>\s]*/g, toCleanUrl),
    );
  },
};

